#!/bin/bash
# VER-1: compute the build version from git history and embed it into BOTH
# the C++ server and the Swift client. Single source of truth — the two
# embeddings can never drift because they are written by the same run.
#
#   usage: gen_version_info.sh <repo-root>
#   writes: <repo-root>/dedup_server/generated/version_info.hpp
#           <repo-root>/swift_ui/Sources/swift_ui/Generated/VersionInfo.swift
#
# Scheme (dedup_server/docs/todo_version_management.md §2):
#   major  = from version.rules (human-managed)
#   minor  = merge commits since major_base  → every PR merge to main bumps it
#   patch  = non-merge commits since the last merge commit
#
# Outputs are only replaced when their content changed, so the CMake
# every-build invocation does not trigger recompiles on unchanged trees.
set -euo pipefail

if [ $# -ne 1 ]; then
    echo "usage: $0 <repo-root>" >&2
    exit 2
fi
ROOT="$(cd "$1" && pwd)"
RULES="$ROOT/version.rules"
HPP="$ROOT/dedup_server/generated/version_info.hpp"
SWIFT="$ROOT/swift_ui/Sources/swift_ui/Generated/VersionInfo.swift"

# --- read version.rules (fail loudly: a silently wrong version defeats VER-1)
if [ ! -f "$RULES" ]; then
    echo "gen_version_info: $RULES not found" >&2
    exit 1
fi
MAJOR=""
MAJOR_BASE=""
while IFS= read -r line; do
    line="${line%%#*}"                       # strip comments
    key="$(echo "${line%%=*}" | tr -d '[:space:]')"
    val="$(echo "${line#*=}" | tr -d '[:space:]')"
    case "$key" in
        major)      MAJOR="$val" ;;
        major_base) MAJOR_BASE="$val" ;;
        *)          ;;                       # unknown keys ignored (forward compat)
    esac
done < "$RULES"
case "$MAJOR" in
    ''|*[!0-9]*) echo "gen_version_info: bad or missing 'major' in $RULES" >&2; exit 1 ;;
esac
if ! echo "$MAJOR_BASE" | grep -Eq '^[0-9a-f]{40}$'; then
    echo "gen_version_info: bad or missing 'major_base' in $RULES" >&2
    exit 1
fi

# --- derive from git; tarball builds (no .git) get the fixed nogit identity
if git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1; then
    BRANCH="$(git -C "$ROOT" rev-parse --abbrev-ref HEAD)"
    COMMIT="$(git -C "$ROOT" rev-parse --short=8 HEAD)"
    if [ -n "$(git -C "$ROOT" status --porcelain)" ]; then DIRTY=true; else DIRTY=false; fi
    MINOR="$(git -C "$ROOT" rev-list --count --merges "${MAJOR_BASE}..HEAD")"
    LAST_MERGE="$(git -C "$ROOT" rev-list --merges -n 1 HEAD || true)"
    PATCH_BASE="${LAST_MERGE:-$MAJOR_BASE}"
    PATCH="$(git -C "$ROOT" rev-list --count "${PATCH_BASE}..HEAD")"
    VERSION="${MAJOR}.${MINOR}.${PATCH}"
else
    BRANCH="nogit"
    COMMIT="unknown"
    DIRTY=false
    VERSION="0.0.0"
fi

# --- display string (§3.2): version on main, branch elsewhere; '*' if dirty
if [ "$BRANCH" = "main" ]; then FIRST="v${VERSION}"; else FIRST="$BRANCH"; fi
if [ "$DIRTY" = true ]; then FIRST="${FIRST}*"; fi
DISPLAY="${FIRST} ${COMMIT}"

# --- write-if-changed
replace_if_changed() {
    local target="$1" tmp="$2"
    mkdir -p "$(dirname "$target")"
    if cmp -s "$tmp" "$target" 2>/dev/null; then
        rm -f "$tmp"
    else
        mv "$tmp" "$target"
    fi
}

TMP_HPP="$(mktemp)"
cat > "$TMP_HPP" <<EOF
// GENERATED by scripts/gen_version_info.sh — do not edit, do not commit.
#pragma once
namespace MediaDedup { namespace VersionInfo {
inline constexpr const char *kVersion = "${VERSION}";
inline constexpr const char *kBranch  = "${BRANCH}";
inline constexpr const char *kCommit  = "${COMMIT}";
inline constexpr bool        kDirty   = ${DIRTY};
// Version on main builds, branch name elsewhere, '*' when dirty (VER-1 §7).
inline constexpr const char *kDisplay = "${DISPLAY}";
}} // namespace MediaDedup::VersionInfo
EOF
replace_if_changed "$HPP" "$TMP_HPP"

TMP_SWIFT="$(mktemp)"
cat > "$TMP_SWIFT" <<EOF
// GENERATED by scripts/gen_version_info.sh — do not edit, do not commit.
enum VersionInfo {
    static let version = "${VERSION}"
    static let branch  = "${BRANCH}"
    static let commit  = "${COMMIT}"
    static let dirty   = ${DIRTY}
    static let display = "${DISPLAY}"
}
EOF
replace_if_changed "$SWIFT" "$TMP_SWIFT"

echo "gen_version_info: ${DISPLAY}"
